"""Hidden-profile cases (idea 3, the less numeric version): choose one of several café sites.

The design follows the hidden-profile paradigm of Stasser & Titus (1985). Each site has
`clues_per_site` verbal clues drawn from `consensus.hp_clues.CLUE_BANK`, each with a hidden value
v in {-2, -1, +1, +2}. A site's true worth is the sum of its clue values, and the best site
(pooled argmax) is the correct choice. Each clue is

- shared (both twins see it) with probability `p_shared`, otherwise
- seen by A only or by B only, with probability 1/2 each.

`p_shared` plays the role rho played in the numeric task: the more is shared, the less each twin
misses. A twin's own view of a site is the sum over the clues it sees.

Two kinds of case are generated by rejection sampling:

- hidden: the pooled best site is unique by at least `min_margin`, and neither twin's own view
  favours it (each twin's own best is another site, by at least 1). Only by pooling unshared clues
  can the team find the best site.
- control: the pooled best site is unique by `min_margin` and is also each twin's own favourite;
  discussion is not needed, and should not hurt.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from consensus.hp_clues import CLUE_BANK

SEEN_BY = ("both", "A", "B")


@dataclass(frozen=True)
class Clue:
    """One clue about one site: `seen_by` is 'both', 'A' or 'B'."""

    bank_id: int
    site: int  # 0-based
    value: int
    text: str
    keywords: tuple[str, ...]
    seen_by: str

    def visible_to(self, twin: str) -> bool:
        return self.seen_by in ("both", twin)


@dataclass
class Case:
    """One decision: `n_sites` sites and their clues; `kind` is 'hidden' or 'control'."""

    n_sites: int
    clues: list[Clue]
    kind: str
    worth: np.ndarray = field(init=False)  # pooled value per site

    def __post_init__(self) -> None:
        self.worth = self.view(None)

    @property
    def best(self) -> int:
        return int(np.argmax(self.worth))

    def view(self, twin: str | None) -> np.ndarray:
        """Sum of clue values per site, over all clues (twin=None) or those `twin` sees."""
        out = np.zeros(self.n_sites)
        for c in self.clues:
            if twin is None or c.visible_to(twin):
                out[c.site] += c.value
        return out

    def clues_for(self, twin: str, site: int) -> list[Clue]:
        return [c for c in self.clues if c.site == site and c.visible_to(twin)]

    def to_dict(self) -> dict:
        return {
            "kind": self.kind,
            "best": self.best,
            "worth": self.worth.tolist(),
            "view_A": self.view("A").tolist(),
            "view_B": self.view("B").tolist(),
            "clues": [
                dict(bank_id=c.bank_id, site=c.site, value=c.value, seen_by=c.seen_by)
                for c in self.clues
            ],
        }


def _margin_best(v: np.ndarray) -> tuple[int, float]:
    """Argmax of v and its margin over the runner-up."""
    order = np.argsort(v)[::-1]
    return int(order[0]), float(v[order[0]] - v[order[1]])


class HiddenProfileGenerator:
    """Samples hidden-profile and control cases (see the module docstring).

    Parameters
    ----------
    n_sites, clues_per_site : int
        Sites per case and clues per site (clues are distinct within a case).
    p_shared : float
        Probability that a clue is seen by both twins.
    min_margin : float
        Required margin of the pooled best site over the runner-up.
    max_tries : int
        Rejection-sampling budget per case.
    """

    def __init__(
        self,
        n_sites: int = 3,
        clues_per_site: int = 6,
        p_shared: float = 0.5,
        min_margin: float = 2.0,
        max_tries: int = 100_000,
    ) -> None:
        if n_sites * clues_per_site > len(CLUE_BANK):
            raise ValueError("not enough clues in the bank for distinct clues per case")
        self.n_sites, self.k = n_sites, clues_per_site
        self.p_shared, self.min_margin, self.max_tries = p_shared, min_margin, max_tries

    def _draw(self, rng: np.random.Generator, kind: str) -> Case:
        ids = rng.choice(len(CLUE_BANK), size=self.n_sites * self.k, replace=False)
        p_one = (1 - self.p_shared) / 2
        seen = rng.choice(3, size=len(ids), p=[self.p_shared, p_one, p_one])
        clues = []
        for j, (i, s) in enumerate(zip(ids, seen)):
            value, text, kw = CLUE_BANK[i]
            clues.append(Clue(int(i), j // self.k, value, text, kw, SEEN_BY[s]))
        return Case(self.n_sites, clues, kind)

    def _accept(self, case: Case) -> bool:
        best, margin = _margin_best(case.worth)
        if margin < self.min_margin:
            return False
        own = [_margin_best(case.view(t)) for t in "AB"]
        if case.kind == "hidden":
            return all(b != best and m >= 1 for b, m in own)
        return all(b == best and m >= 1 for b, m in own)

    def sample(self, rng: np.random.Generator, kind: str) -> Case:
        """One case of the given kind ('hidden' or 'control')."""
        if kind not in ("hidden", "control"):
            raise ValueError(f"kind must be 'hidden' or 'control', got {kind!r}")
        for _ in range(self.max_tries):
            case = self._draw(rng, kind)
            if self._accept(case):
                return case
        raise RuntimeError(f"no {kind} case found in {self.max_tries} tries (p_shared too high?)")

    def sample_set(self, rng: np.random.Generator, n_hidden: int, n_control: int) -> list[Case]:
        """`n_hidden` + `n_control` cases in random order."""
        kinds = np.array(["hidden"] * n_hidden + ["control"] * n_control)
        rng.shuffle(kinds)
        return [self.sample(rng, str(k)) for k in kinds]
